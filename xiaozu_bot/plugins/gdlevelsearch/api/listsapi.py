class Lists:
    @staticmethod
    def search_level(id_value: int|str):
        """
        在 IDL、HDL、MDL、EDL 四个列表中搜索 id。
        匹配成功返回形如 "IDL #20" 的字符串，否则返回 None。
        """
        try:
            target = int(id_value)
        except (TypeError, ValueError):
            return None

        if id_value == 0:
            return None

        for name, level_list in (
            ("IDL", IDL),
            ("HDL", HDL),
            ("MDL", MDL),
            ("EDL", EDL),
        ):
            try:
                idx = level_list.index(target)
            except ValueError:
                continue
            return f"{name} #{idx}"

        return None
